#!/usr/bin/env python3
"""Bake an SVG into a half-block terminal banner.

A terminal cannot draw vector art, so the mark is rasterised and each character
cell carries two pixels: the foreground paints the top half, the background the
bottom half. Composited on the banner background, so no transparency handling is
needed at runtime.

    python3 scripts/svg_banner.py --svg assets/skynet-matrix.svg --cols 32 \
        --out src/welcome_banner.rs

Requires rsvg-convert and ffmpeg.
"""

import argparse
import subprocess
from pathlib import Path

BACKGROUND = (0x30, 0x30, 0x30)


def rasterise(svg: str, width: int, height: int) -> bytes:
    png = "/tmp/svg_banner.png"
    subprocess.run(
        ["rsvg-convert", "-w", str(width), "-h", str(height), "-b", "#303030", svg, "-o", png],
        check=True,
    )
    return subprocess.run(
        ["ffmpeg", "-loglevel", "error", "-i", png, "-f", "rawvideo", "-pix_fmt", "rgb24", "-"],
        capture_output=True,
        check=True,
    ).stdout


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--svg", required=True)
    parser.add_argument("--cols", type=int, default=32)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    # Preserve the aspect ratio; each cell is two pixels tall.
    import re

    text = Path(args.svg).read_text(encoding="utf-8")
    view = re.search(r'viewBox="([\d.\- ]+)"', text)
    _, _, vb_w, vb_h = (float(v) for v in view.group(1).split())
    px_w = args.cols
    px_h = max(2, round(px_w * vb_h / vb_w / 2) * 2)
    rows = px_h // 2

    raw = rasterise(args.svg, px_w, px_h)
    if len(raw) != px_w * px_h * 3:
        raise SystemExit("unexpected raster size")

    cells = []
    for y in range(rows):
        row = []
        for x in range(px_w):
            top = raw[((y * 2) * px_w + x) * 3:((y * 2) * px_w + x) * 3 + 3]
            bottom = raw[((y * 2 + 1) * px_w + x) * 3:((y * 2 + 1) * px_w + x) * 3 + 3]
            row.append("{:02x}{:02x}{:02x}{:02x}{:02x}{:02x}".format(*top, *bottom))
        cells.append("".join(row))

    lines = [
        "//! Generated by scripts/svg_banner.py — do not edit by hand.",
        "//! Each cell is 12 hex characters: the top pixel then the bottom pixel.",
        "",
        f"pub const BANNER_COLS: usize = {px_w};",
        f"pub const BANNER_ROWS: usize = {rows};",
        "",
        "pub const BANNER: &[&str] = &[",
    ]
    lines += [f'    "{row}",' for row in cells]
    lines += ["];", ""]
    Path(args.out).write_text("\n".join(lines), encoding="utf-8")
    print(f"{px_w} cols x {rows} rows -> {args.out}")


if __name__ == "__main__":
    main()
