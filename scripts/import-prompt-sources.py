#!/usr/bin/env python3
"""Generate src/tui_prompt_sources.rs from a Feishu record-list ndjson snapshot.

The table is the source layer: 56 verbatim rows. Rows are grouped by
(author, topic) so one drawer entry carries the complete text of that topic
instead of a curated paraphrase. Labels/categories are metadata only.

Usage:
    python3 -I scripts/import-prompt-sources.py <records.ndjson> <output.rs>
"""

import json
import sys
from pathlib import Path

CATEGORY_ORDER = [
    "先想再做",
    "先验证再算完",
    "抬高目标",
    "简单优先",
    "只改必须改的",
    "按高手的方法做",
    "换视角与阵容",
    "换输出形态",
    "固定形式",
    "给原料",
    "加情绪诉求",
    "用例子定调",
]
CATEGORY_INDEX = {name: index for index, name in enumerate(CATEGORY_ORDER)}


def first(record, field):
    value = record.get(field)
    if isinstance(value, list):
        value = value[0] if value else None
    if value is None:
        return ""
    return str(value).strip()


def clean(value):
    return "".join(
        character if character in "\n\t" or ord(character) >= 0x20 else " "
        for character in value
    )


def literal(value):
    return json.dumps(clean(value), ensure_ascii=False)


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    source = Path(sys.argv[1])
    output = Path(sys.argv[2])
    records = [json.loads(line) for line in source.read_text().splitlines() if line.strip()]

    groups = {}
    for record in records:
        author = first(record, "作者") or "未标注"
        topic = first(record, "主题") or record.get("record_id", "未命名")
        groups.setdefault((author, topic), []).append(record)

    rows = []
    for (author, topic), members in groups.items():
        category = next(
            (first(record, "共性分类") for record in members if first(record, "共性分类")),
            "未分类",
        )
        natures = [first(record, "性质") for record in members if first(record, "性质")]
        nature = "本人原文" if "本人原文" in natures else (natures[0] if natures else "未标注")
        original = "\n\n".join(
            first(record, "原文（英文逐字）")
            for record in members
            if first(record, "原文（英文逐字）")
        )
        translation = "\n\n".join(
            first(record, "中文直译") for record in members if first(record, "中文直译")
        )
        source_doc = next(
            (first(record, "出处") for record in members if first(record, "出处")), ""
        )
        link = next(
            (first(record, "链接") for record in members if first(record, "链接")), ""
        )
        date = next(
            (first(record, "日期")[:10] for record in members if first(record, "日期")), ""
        )
        record_ids = ", ".join(
            record.get("record_id", "") for record in members if record.get("record_id")
        )
        rows.append(
            {
                "id": f"source-{topic.lower().replace(' ', '-')}" if topic else "source",
                "author": author,
                "topic": topic,
                "category": category,
                "nature": nature,
                "original": original,
                "translation": translation,
                "source_doc": source_doc,
                "link": link,
                "date": date,
                "record_ids": record_ids,
                "fragments": len(members),
            }
        )

    rows.sort(
        key=lambda row: (
            CATEGORY_INDEX.get(row["category"], len(CATEGORY_ORDER)),
            row["author"],
            row["topic"],
        )
    )

    lines = [
        "//! Generated by scripts/import-prompt-sources.py from the Feishu prompt table.",
        "//! Source snapshot: docs/evidence/prompt-sources-2026-11-11.ndjson (56 rows).",
        "//! Labels and categories are curation; `original` and `translation` are complete.",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct PromptSourceGroup {",
        "    pub id: &'static str,",
        "    pub author: &'static str,",
        "    pub topic: &'static str,",
        "    pub category: &'static str,",
        "    pub nature: &'static str,",
        "    pub original: &'static str,",
        "    pub translation: &'static str,",
        "    pub source_doc: &'static str,",
        "    pub link: &'static str,",
        "    pub date: &'static str,",
        "    pub record_ids: &'static str,",
        "    pub fragments: usize,",
        "}",
        "",
        "pub const PROMPT_SOURCE_GROUPS: &[PromptSourceGroup] = &[",
    ]
    for row in rows:
        lines.extend(
            [
                "    PromptSourceGroup {",
                f"        id: {literal(row['id'])},",
                f"        author: {literal(row['author'])},",
                f"        topic: {literal(row['topic'])},",
                f"        category: {literal(row['category'])},",
                f"        nature: {literal(row['nature'])},",
                f"        original: {literal(row['original'])},",
                f"        translation: {literal(row['translation'])},",
                f"        source_doc: {literal(row['source_doc'])},",
                f"        link: {literal(row['link'])},",
                f"        date: {literal(row['date'])},",
                f"        record_ids: {literal(row['record_ids'])},",
                f"        fragments: {row['fragments']},",
                "    },",
            ]
        )
    lines.extend(["];", ""])
    output.write_text("\n".join(lines))
    print(f"wrote {len(rows)} groups from {len(records)} rows to {output}")


if __name__ == "__main__":
    main()
